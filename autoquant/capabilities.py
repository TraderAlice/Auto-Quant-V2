def descriptor(
    command_id: str,
    usage: str,
    description: str,
    effect: str,
    arguments: list[dict[str, Any]],
    *,
    supports_json: bool = True,
) -> dict[str, Any]:
    return {
        "id": command_id,
        "usage": usage,
        "description": description,
        "effect": effect,
        "supportsJson": supports_json,
        "exitCodes": EXIT_CODES,
        "arguments": arguments,
        "outputSections": [],
    }


